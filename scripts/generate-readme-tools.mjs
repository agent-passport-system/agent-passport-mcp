#!/usr/bin/env node
// Regenerates the tool tables in README.md from the running server.
//
// Reads tools/list over stdio from build/index.js (run `npm run build` first),
// groups tools by the delegation scope in TOOL_SCOPE_MAP, and rewrites the block
// between the README markers below. Every row's name, title, hints and
// description come from what an MCP client receives, so the README cannot list
// a tool the server does not register, and cannot miss one it does.
//
//   node scripts/generate-readme-tools.mjs          rewrite README.md
//   node scripts/generate-readme-tools.mjs --check  exit 1 if README.md is stale
//
// tests/tool-annotations.test.mjs runs the --check comparison.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { listToolsOverStdio } from "./lib/list-tools.mjs";

const README = fileURLToPath(new URL("../README.md", import.meta.url));
export const START = "<!-- tools:start (generated by scripts/generate-readme-tools.mjs, do not hand-edit) -->";
export const END = "<!-- tools:end -->";

const GROUPS = [
  ["*", "Meta"],
  ["identity", "Identity and key rotation"],
  ["delegation", "Delegation and escalation"],
  ["principal", "Principal identity"],
  ["reputation", "Reputation-gated authority"],
  ["coordination", "Coordination and provisional statements"],
  ["communication", "Agora and agent messaging"],
  ["governance", "Governance, charters, provenance, attribution"],
  ["commerce", "Commerce"],
  ["data", "Data governance"],
  ["gateway", "Gateway (removed in v3.0.0, stubs return a migration notice)"],
  ["network", "Intent Network"],
  ["temporal", "Time and reserve attestation"],
  ["attribution", "Attribution weights"],
  ["settlement", "Attribution settlement"],
  ["capability", "Capability token v0.1"],
  ["mutual-auth", "Mutual authentication"],
];

function firstSentence(text) {
  const t = (text || "").replace(/\s+/g, " ").trim();
  const m = t.match(/^(.+?[.!?])(\s|$)/);
  let s = m ? m[1] : t;
  if (s.length > 180) s = s.slice(0, 177).trimEnd() + "...";
  return s.replace(/\|/g, "\\|");
}

const yes = (b) => (b ? "yes" : "");

export async function renderToolsBlock() {
  const mod = await import("../build/index.js");
  mod.createSandboxServer();
  const scopeMap = mod.TOOL_SCOPE_MAP;
  const tools = await listToolsOverStdio();

  const byScope = new Map();
  for (const t of tools) {
    const scope = scopeMap[t.name] ?? "other";
    if (!byScope.has(scope)) byScope.set(scope, []);
    byScope.get(scope).push(t);
  }
  const known = new Set(GROUPS.map(([s]) => s));
  const order = [...GROUPS];
  for (const s of byScope.keys()) if (!known.has(s)) order.push([s, s === "other" ? "Other" : s]);

  const lines = [START, "", `## Tools (${tools.length})`, ""];
  lines.push(
    "Every tool carries MCP annotations. **Read-only** means the tool writes no file, calls no mutating remote endpoint and changes no session state other tools read. " +
    "**Destructive** means it deletes, revokes, supersedes or irreversibly consumes something. " +
    "**Network** means it can contact an external host (see [Network and local files](#network-and-local-files)). " +
    "The hint values live in `src/toolAnnotations.ts`.",
    "",
  );
  for (const [scope, label] of order) {
    const group = byScope.get(scope);
    if (!group || group.length === 0) continue;
    group.sort((a, b) => a.name.localeCompare(b.name));
    lines.push(`### ${label}: ${group.length} tool${group.length === 1 ? "" : "s"}`, "");
    lines.push("| Tool | Title | Read-only | Destructive | Network | Description |");
    lines.push("|------|-------|-----------|-------------|---------|-------------|");
    for (const t of group) {
      const a = t.annotations || {};
      lines.push(`| \`${t.name}\` | ${t.title ?? a.title ?? ""} | ${yes(a.readOnlyHint)} | ${yes(a.destructiveHint)} | ${yes(a.openWorldHint)} | ${firstSentence(t.description)} |`);
    }
    lines.push("");
  }
  lines.push(END);
  return lines.join("\n");
}

export function spliceReadme(readme, block) {
  const s = readme.indexOf(START);
  const e = readme.indexOf(END);
  if (s < 0 || e < 0 || e < s) throw new Error("README.md is missing the tools:start / tools:end markers");
  return readme.slice(0, s) + block + readme.slice(e + END.length);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const block = await renderToolsBlock();
  const current = readFileSync(README, "utf8");
  const next = spliceReadme(current, block);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error("README.md tool tables are stale. Run: node scripts/generate-readme-tools.mjs");
      process.exit(1);
    }
    console.log("README.md tool tables are current.");
  } else {
    writeFileSync(README, next);
    console.log("README.md tool tables regenerated.");
  }
  process.exit(0);
}
